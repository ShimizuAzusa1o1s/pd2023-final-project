Map::Map(){
    //Loading map materials into the program.
    this->dirt = TextureManager::loadTexture( "assets/Dirt.bmp" );
    this->grass = TextureManager::loadTexture( "assets/Grass.bmp" );
    this->water = TextureManager::loadTexture( "assets/Water.bmp" );

    //Loading map information.
    loadMap( firstLevel );

    //Setting initial position.
    this->srcRect.x = this->srcRect.y = 0;
    this->destRect.x = this->destRect.y = 0;

    this->srcRect.w = this->destRect.w = 32;
    this->srcRect.h = this->destRect.h = 32;
}

void Map::loadMap( int arr[20][25] ){
    for( int i = 0; i < 20; i++ ){
        for( int j = 0; j < 25; j++ ){
            this->map[i][j] = arr[i][j];
        }
    }
}

void Map::drawMap(){
    int type = 0;
    for( int i = 0; i < 20; i++ ){
        for( int j = 0; j < 25; j++ ){
            type = map[i][j];
            //As the map-drawing process goes, the rendering position should be updated, too.
            this->destRect.x = j * 32;
            this->destRect.y = i * 32;
            switch( type )
            {
                case 0:
                    TextureManager::draw( water, srcRect, destRect );
                    break;
                case 1:
                    TextureManager::draw( grass, srcRect, destRect );
                    break;
                case 2:
                    TextureManager::draw( dirt, srcRect, destRect );
                    break;
                default:
                    break;
            }
        }
    }
}